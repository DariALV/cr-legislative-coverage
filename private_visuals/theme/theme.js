// Look of every local page: the mode ("system", "light" or "dark") and the style ("oficial" by default, or one of
// LC.STYLES, defined in variants.css). Both are kept in the browser per origin; "system" follows the OS. Loaded as a
// classic script in <head> so html[data-theme] and html[data-style] are set before the page paints (no flash).
// Pages that draw with colors read from CSS (SVG, canvas) listen for the "themechange" event on document, which
// fires whenever the mode or the style changes, and redraw.
// Helpers: LC.css("--cat-1") gives the current resolved value of a token, LC.cat(i) the i-th categorical color
// (cycling), LC.mix(a, b, t) blends two hex colors.
window.LC = {
  css: (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim(),
  cat: (i) => window.LC.css(`--cat-${(i % 8) + 1}`),
  mix(a, b, t) {
    const rgb = (h) => [1, 3, 5].map((k) => parseInt(h.slice(k, k + 2), 16));
    const x = rgb(a), y = rgb(b);
    return "#" + x.map((v, i) => Math.round(v + (y[i] - v) * t).toString(16).padStart(2, "0")).join("");
  },
};

